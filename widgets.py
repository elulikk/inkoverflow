def _dark_palette():
    pal = QPalette()
    roles = {
        QPalette.Window: "bg", QPalette.WindowText: "text", QPalette.Base: "base",
        QPalette.AlternateBase: "card", QPalette.Text: "text", QPalette.Button: "header",
        QPalette.ButtonText: "text", QPalette.ToolTipBase: "card", QPalette.ToolTipText: "text",
        QPalette.PlaceholderText: "muted", QPalette.Link: "blue", QPalette.BrightText: "bad",
    }
    for role, key in roles.items():
        pal.setColor(role, QColor(C[key]))
    pal.setColor(QPalette.Highlight, QColor("#2f6f8f"))
    pal.setColor(QPalette.HighlightedText, QColor("#ffffff"))
    for role in (QPalette.WindowText, QPalette.Text, QPalette.ButtonText):
        pal.setColor(QPalette.Disabled, role, QColor(C["disabled"]))
    return pal


def apply_theme(app, dark):
    """Switch the whole application between the light and the dark theme."""
    global _dark
    _dark = bool(dark)
    C.clear()
    C.update(THEMES["dark" if _dark else "light"])
    if _dark:
        app.setStyle("Fusion")  # the native Vista style ignores palettes
        app.setPalette(_dark_palette())
    else:
        keys = QStyleFactory.keys()
        app.setStyle("windowsvista" if "windowsvista" in keys else "Fusion")
        app.setPalette(app.style().standardPalette())
    app.setStyleSheet(build_qss())


