RIBBON_BUTTON_HEIGHT = 76


class RibbonButton(QToolButton):
    """Ribbon command. Hovering shows a tip with the name, what it does and, when the
    button is off, why: the widget's own toolTip() holds only that reason ('' when it
    is enabled), so the rest of the app can keep setting it."""

    def __init__(self, icon_name, text, desc, large=True, shortcut=""):
        super().__init__()
        self.setObjectName("rbtn")
        self.title = text.replace("\n", " ")
        self.desc, self.shortcut = desc, shortcut
        self.setText(text)
        self.setIcon(icons.icon(icon_name))
        self.setAutoRaise(True)
        self.setCursor(Qt.ArrowCursor)
        if large:
            self.setToolButtonStyle(Qt.ToolButtonTextUnderIcon)
            self.setIconSize(QSize(32, 32))
            self.setMinimumWidth(56)
            self.setFixedHeight(RIBBON_BUTTON_HEIGHT)
        else:
            self.setToolButtonStyle(Qt.ToolButtonTextBesideIcon)
            self.setIconSize(QSize(16, 16))
            self.setFixedHeight(22)

    def rich_tip(self):
        head = f"<b>{escape(self.title)}</b>"
        if self.shortcut:
            head += f" <span style='color:{C['muted']}'>({escape(self.shortcut)})</span>"
        body = f"{head}<br>{escape(self.desc)}" if self.desc else head
        why = self.toolTip()
        if why:
            body += (f"<br><br><span style='color:{C['bad']}'><b>No disponible:</b> "
                     f"{escape(why)}</span>")
        return f"<table width='330'><tr><td>{body}</td></tr></table>"

    def event(self, e):
        if e.type() == QEvent.ToolTip:
            QToolTip.showText(e.globalPos(), self.rich_tip(), self)
            return True
        return super().event(e)


class RibbonGroup(QFrame):
    """One labelled block of commands; columns of small controls or large buttons."""

    def __init__(self, title):
        super().__init__()
        self.setObjectName("rgroup")
        outer = QVBoxLayout(self)
        outer.setContentsMargins(4, 3, 4, 1)
        outer.setSpacing(0)
        self.row = QHBoxLayout()
        self.row.setSpacing(2)
        outer.addLayout(self.row, 1)
        label = QLabel(title)
        label.setObjectName("rgroupTitle")
        label.setAlignment(Qt.AlignCenter)
        outer.addWidget(label)

    def add(self, widget):
        self.row.addWidget(widget, 0, Qt.AlignTop)
        return widget

    def column(self, *items, width=None):
        """Small controls stacked; a str item becomes a caption label."""
        box = QWidget()
        lay = QVBoxLayout(box)
        lay.setContentsMargins(2, 2, 2, 0)
        lay.setSpacing(3)
        for item in items:
            if isinstance(item, str):
                item = QLabel(item)
                item.setObjectName("rlabel")
            lay.addWidget(item)
        lay.addStretch()
        if width:
            box.setFixedWidth(width)
        self.row.addWidget(box)
        return box


