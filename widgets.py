class Gauge(QWidget):
    """Level of one waste-ink pad as a classic horizontal meter with the 70 % and
    90 % warning marks."""

    def __init__(self, title):
        super().__init__()
        self.title, self.value, self.detail = title, None, ""
        self.setMinimumSize(280, 74)

    def set_value(self, value, detail=""):
        self.value, self.detail = value, detail
        self.update()

    @staticmethod
    def color_for(value):
        if value is None:
            return QColor(C["muted"])
        return QColor(C["g_ok"] if value < 70 else C["g_warn"] if value < 90 else C["g_bad"])

    def paintEvent(self, _):
        p = QPainter(self)
        p.setRenderHint(QPainter.Antialiasing)
        w = self.width()
        bar = QRectF(1.5, 21.5, w - 3, 18)

        p.setFont(QFont("Segoe UI", 9, QFont.DemiBold))
        p.setPen(QColor(C["text"]))
        p.drawText(QRect(0, 0, w - 90, 18), Qt.AlignLeft | Qt.AlignVCenter, self.title)
        text = "--" if self.value is None else f"{self.value:.1f} %"
        p.setFont(QFont("Segoe UI", 11, QFont.Bold))
        p.setPen(self.color_for(self.value).darker(115) if self.value is not None
                 else QColor(C["muted"]))
        p.drawText(QRect(w - 120, 0, 120, 18), Qt.AlignRight | Qt.AlignVCenter, text)

        well = QLinearGradient(0, bar.top(), 0, bar.bottom())
        well.setColorAt(0, QColor(C["well0"]))
        well.setColorAt(1, QColor(C["well1"]))
        p.setPen(QPen(QColor(C["wellline"]), 1))
        p.setBrush(well)
        p.drawRect(bar)
        if self.value is not None and self.value > 0:
            fill = QRectF(bar.left() + 1.5, bar.top() + 1.5,
                          (bar.width() - 3) * min(self.value, 100) / 100, bar.height() - 3)
            base = self.color_for(self.value)
            grad = QLinearGradient(0, fill.top(), 0, fill.bottom())
            grad.setColorAt(0, base.lighter(135))
            grad.setColorAt(0.5, base)
            grad.setColorAt(1, base.darker(112))
            p.setPen(Qt.NoPen)
            p.setBrush(grad)
            p.drawRect(fill)

        # scale: a tick every 10 %, labels at 0/50/100, warning marks at 70 and 90
        p.setFont(QFont("Segoe UI", 7))
        for pct in range(0, 101, 10):
            x = bar.left() + (bar.width()) * pct / 100
            p.setPen(QPen(QColor(C["wellline"]), 1))
            p.drawLine(int(x), int(bar.bottom()) + 1, int(x), int(bar.bottom()) + (5 if pct % 50 == 0 else 3))
        for pct, color in ((70, C["g_warn"]), (90, C["g_bad"])):
            x = bar.left() + bar.width() * pct / 100
            p.setPen(QPen(QColor(color), 1.4, Qt.DashLine))
            p.drawLine(int(x), int(bar.top()) - 3, int(x), int(bar.bottom()))
        p.setPen(QColor(C["muted"]))
        p.setFont(QFont("Segoe UI", 8))
        p.drawText(QRect(0, int(bar.bottom()) + 6, w, 16), Qt.AlignLeft | Qt.AlignVCenter,
                   self.detail)
        p.drawText(QRect(0, int(bar.bottom()) + 6, w, 16), Qt.AlignRight | Qt.AlignVCenter,
                   "aviso 70 % · crítico 90 %")


class InkMeter(QWidget):
    """One ink colour: a vertical tank filled with its colour, the level under it. With
    level None (a tank the printer does not measure) the tank is drawn empty and hatched
    and says 'no medido' instead of a number, or `state`: what a low-ink sensor says
    (HP: 'con tinta', 'bajo', 'vacío')."""

    def __init__(self, name, swatch, level=None, state=""):
        super().__init__()
        self.name, self.swatch, self.level, self.state = name, swatch, level, state
        self.setMinimumSize(64, 96)
        if level is not None:
            tip = f"{level} % (estimado por la impresora)"
        elif state:
            tip = f"{state} (sensor de tinta baja; la impresora no da un porcentaje)"
        else:
            tip = "la impresora no mide este tanque"
        self.setToolTip(f"{name}: {tip}")

    def paintEvent(self, _):
        p = QPainter(self)
        p.setRenderHint(QPainter.Antialiasing)
        w, h = self.width(), self.height()
        tank = QRectF(w / 2 - 14, 4.5, 28, h - 44)
        p.setPen(QPen(QColor(C["wellline"]), 1))
        p.setBrush(QColor(C["well0"]))
        p.drawRoundedRect(tank, 3, 3)
        colour = QColor(self.swatch)
        if self.level is None:
            hatch = QColor(colour)
            hatch.setAlpha(110)
            p.setPen(Qt.NoPen)
            p.setBrush(QBrush(hatch, Qt.BDiagPattern))
            p.drawRoundedRect(tank.adjusted(1.5, 1.5, -1.5, -1.5), 2, 2)
        elif self.level > 0:
            inner = tank.adjusted(1.5, 1.5, -1.5, -1.5)
            height = inner.height() * min(self.level, 100) / 100
            fill = QRectF(inner.left(), inner.bottom() - height, inner.width(), height)
            # outlined so black ink stays visible on the dark theme's well
            p.setPen(QPen(QColor(C["wellline"]), 1))
            p.setBrush(colour)
            p.drawRoundedRect(fill, 2, 2)
        p.setPen(QColor(C["text"]))
        p.setFont(QFont("Segoe UI", 8, QFont.DemiBold))
        p.drawText(QRect(0, int(tank.bottom()) + 4, w, 16), Qt.AlignCenter, self.name)
        low = (self.level is not None and self.level <= 15) or self.state in (
            "bajo", "muy bajo", "vacío", "falta")
        p.setPen(QColor(C["bad"] if low else C["muted"]))
        p.setFont(QFont("Segoe UI", 8))
        p.drawText(QRect(0, int(tank.bottom()) + 20, w, 16), Qt.AlignCenter,
                   f"{self.level} %" if self.level is not None else self.state or "no medido")


class TaskSignals(QObject):
    done = Signal(object, object, object)  # callback, result, error or None


class Task(QRunnable):
    """Runs fn() on the thread pool. The result is emitted with its callback so
    that a QObject slot on the UI thread can run it (a bare lambda slot would
    run on the worker thread)."""

    def __init__(self, fn, callback):
        super().__init__()
        self.fn, self.callback = fn, callback
        self.signals = TaskSignals()

    def run(self):
        try:
            result, error = self.fn(), None
        except Exception as exc:  # reported to the user, never swallowed
            result, error = None, str(exc) or exc.__class__.__name__
        self.signals.done.emit(self.callback, result, error)
