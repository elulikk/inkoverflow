def app_icon():
    """Window / taskbar icon from the brand PNGs (empty icon if they are missing)."""
    icon = QIcon()
    for size in ICON_SIZES:
        path = BRAND / f"icon_{size}.png"
        if path.is_file():
            icon.addFile(str(path))
    return icon


def logo_pixmap(width=None, height=None, light=True):
    """The logo scaled to `width` (or `height`) logical pixels, sharp on 2x screens;
    None if the file is missing. light=True is the version for light backgrounds."""
    pixmap = QPixmap(str(BRAND / ("logo_light.png" if light else "logo_dark.png")))
    if pixmap.isNull():
        return None
    if height:
        scaled = pixmap.scaledToHeight(height * 2, Qt.SmoothTransformation)
    else:
        scaled = pixmap.scaledToWidth(width * 2, Qt.SmoothTransformation)
    scaled.setDevicePixelRatio(2.0)
    return scaled


